H('七、财务规划')
P('启动资金约2000元：首批采购保温箱4个（800元）、包装袋/餐盒（500元）、宣传材料（300元）、备用金（400元）。前两周为试运营，免费试吃拉新。预计第3周实现稳定订单，日均200单，月流水3万元。学期末高峰期日均可达500单。寒暑假暂停运营，每学期营业约4个月。')

H('八、风险控制')
P('主要风险：（1）食品安全：只与校内正规食堂和品牌供应商合作，签订供应协议，保留样品备查；（2）配送延误：设定配送时间窗口（7:00-7:30），按宿舍楼分区配送，每人负责一栋楼；（3）天气影响：雨天增加保温防水措施，提前一天关注天气预报；（4）订单波动：预售制锁定订单量，按单采购不囤货。')

