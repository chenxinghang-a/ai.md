from docx import Document
from docx.shared import Pt
from docx.enum.text import WD_ALIGN_PARAGRAPH

doc = Document()
style = doc.styles['Normal']
style.font.size = Pt(12)

def T(text, size=22, bold=True):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    r.font.size = Pt(size); r.font.bold = bold; r.font.name = '黑体'

def H(text):
    h = doc.add_heading(text, level=1)
    for r in h.runs: r.font.name = '黑体'

def P(text):
    p = doc.add_paragraph(text)
    p.paragraph_format.first_line_indent = Pt(24)
    p.paragraph_format.line_spacing = 1.5

for _ in range(6): doc.add_paragraph()
T('商业计划书', 28)
doc.add_paragraph()
T('项目名称：早点到——校园早餐配送服务', 18)
for _ in range(3): doc.add_paragraph()
p = doc.add_paragraph()
p.alignment = WD_ALIGN_PARAGRAPH.CENTER
r = p.add_run('小组成员：陈星行  2022062101  电气工程及其自动化\n（其他成员姓名学号班级）\n\n2026年5月')
r.font.size = Pt(14)
doc.add_page_break()

H('目  录')
for i in ['一、执行摘要','二、项目背景','三、产品与服务','四、市场分析','五、商业模式','六、团队介绍','七、财务规划','八、风险控制']:
    doc.add_paragraph(i).runs[0].font.size = Pt(14)
doc.add_page_break()

