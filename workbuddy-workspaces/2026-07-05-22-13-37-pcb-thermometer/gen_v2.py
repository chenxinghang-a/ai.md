# ===== 样式定义 =====
header_font_w = Font(bold=True, size=11, color="FFFFFF")
header_fill = PatternFill("solid", fgColor="2F5496")
center = Alignment(horizontal="center", vertical="center")
left_center = Alignment(horizontal="left", vertical="center", wrap_text=True)
thin_border = Border(left=Side(style='thin'), right=Side(style='thin'),
                     top=Side(style='thin'), bottom=Side(style='thin'))
jumper_f = PatternFill("solid", fgColor="FFEB9C")     # 黄-飞线
power_f = PatternFill("solid", fgColor="C6EFCE")      # 绿-电源/地
signal_f = PatternFill("solid", fgColor="DDEBF7")     # 蓝-信号
term_f  = PatternFill("solid", fgColor="FCE4D6")      # 橙-端子

def set_header(ws, row, headers):
    for col, h in enumerate(headers, 1):
        c = ws.cell(row=row, column=col, value=h)
        c.font, c.fill, c.alignment, c.border = header_font_w, header_fill, center, thin_border

def add_row(ws, row, data, color_col=None):
    for col, val in enumerate(data, 1):
        c = ws.cell(row=row, column=col, value=val)
        c.alignment = left_center if col > 1 else center
        c.border = thin_border
        if color_col and col in color_col: c.fill = signal_f
        elif "飞线" in str(val): c.fill = jumper_f
        elif "电源" in str(data[3] if len(data)>3 else "") or "地" in str(val): c.fill = power_f


